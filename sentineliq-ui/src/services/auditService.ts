/**
 * Audit Service
 * Manages audit trail operations with mock/real API switching
 */

import { config } from '../lib/config';
import { endpoints } from '../lib/api';
import { simulateApiDelay } from '../hooks/useActions';
import type { AuditEntry } from '../types/index';

